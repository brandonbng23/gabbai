// IANA timezone identifiers for North America, Central America, and the Caribbean.
// US choices also include Hawaii. Source: https://data.iana.org/time-zones/tzdb/zone.tab
export function timezoneLabel(zone: string): string {
    const place = zone.replace(/^(America|Atlantic|Pacific)\//, '').replaceAll('_', ' ').replaceAll('/', ' / ');
    try {
        const name = new Intl.DateTimeFormat('en-US', { timeZone: zone, timeZoneName: 'longGeneric' })
            .formatToParts(new Date()).find(part => part.type === 'timeZoneName')?.value;
        return name ? `${place} — ${name}` : place;
    } catch {
        return place;
    }
}

